-- L'alerte n'est pas stockee : elle est recalculee a chaque lecture a partir des seuils.

--changeset Mody:005-1-create-constante-visite
CREATE TABLE constante_visite
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    visite_id          UUID          NOT NULL,
    type               VARCHAR(20)   NOT NULL,
    creneau            VARCHAR(10)   NOT NULL,
    valeur             NUMERIC(7, 2) NOT NULL,
    -- Renseignee pour la tension arterielle seulement (valeur porte alors la systolique).
    valeur_diastolique NUMERIC(7, 2),
    heure_mesure       TIME,
    CONSTRAINT constante_visite_pkey PRIMARY KEY (id),
    CONSTRAINT fk_constante_visite_visite FOREIGN KEY (visite_id) REFERENCES visite_suivi (id),
    CONSTRAINT constante_visite_visite_type_creneau_key UNIQUE (visite_id, type, creneau)
);
