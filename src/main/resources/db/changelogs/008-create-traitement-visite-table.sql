CREATE TABLE traitement_visite
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    visite_id          UUID         NOT NULL,
    medicament         VARCHAR(255) NOT NULL,
    posologie          VARCHAR(255),
    voie               VARCHAR(100),
    observant          BOOLEAN,
    probleme           BOOLEAN,
    probleme_precision TEXT,
    CONSTRAINT traitement_visite_pkey PRIMARY KEY (id),
    CONSTRAINT fk_traitement_visite_visite FOREIGN KEY (visite_id) REFERENCES visite_suivi (id)
);

--changeset Mody:008-2-index-traitement-visite
CREATE INDEX idx_traitement_visite_visite ON traitement_visite (visite_id);
